void CLuminophoreConfigManager::refreshPaths() {
    const auto               root       = settingsFixtureRoot();
    const auto               generation = CSettingsGenerations(root).completed();
    std::vector<std::string> paths;
    for (const auto* file : {"settings.toml", "monitors.toml", "bindings.toml", "placement.toml", "bundles.toml"})
        paths.push_back((root / "generations" / generation.id / file).string());
    m_paths = std::move(paths);
}
std::string CLuminophoreConfigManager::getMainConfigPath() {
    refreshPaths();
    return m_paths.front();
}
