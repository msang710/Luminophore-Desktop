static std::string canonical(std::string name) {
    std::ranges::replace(name, '.', ':');
    return name;
}

struct CLuminophoreConfigManager::SStorage {
    struct ICell {
        virtual ~ICell()                           = default;
        virtual Config::SConfigOptionReply reply() = 0;
    };
    template <typename T>
    struct SCell final : ICell {
        T     value;
        void* pointer = &value;
        explicit SCell(T initial) : value(std::move(initial)) {
            ;
        }
        Config::SConfigOptionReply reply() override {
            return {.dataptr = &pointer, .type = &typeid(T)};
        }
    };
    std::map<std::string, std::unique_ptr<ICell>> cells;
    template <typename T>
    void add(const std::string& name, T value) {
        if (!cells.emplace(canonical(name), std::make_unique<SCell<T>>(std::move(value))).second)
            throw std::runtime_error("duplicate native config value: " + name);
    }
    template <typename Declaration>
    bool addDefault(const SP<Config::Values::IValue>& declaration) {
        auto* typed = dynamic_cast<Declaration*>(declaration.get());
        if (!typed)
            return false;
        add(declaration->name(), typed->defaultVal());
        return true;
    }
    template <typename T>
    void set(const std::string& name, T value) {
        auto* cell = dynamic_cast<SCell<T>*>(cells.at(canonical(name)).get());
        if (!cell)
            throw std::runtime_error("native config type mismatch: " + name);
        cell->value = std::move(value);
    }
};

